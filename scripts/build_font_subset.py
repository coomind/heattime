"""Build the bundled Korean UI font subset (offline, from the installed @fontsource package).

Keeps KS X 1001 Hangul (2,350 syllables), printable ASCII, and every other character that the app's
own text uses (scanned from frontend/src and frontend/index.html). Writes one WOFF per weight to
frontend/src/fonts/ and a coverage report. `--check` only verifies that every app character is in
the committed subset (used by tests/test_font_subset.py) and exits 1 if one is missing.

Fonts: IBM Plex Sans KR, SIL Open Font License 1.1 (frontend/node_modules/@fontsource/ibm-plex-sans-kr/LICENSE).
WOFF (zlib) is used because the project environment has no Brotli encoder for WOFF2.
"""
import argparse
import json
from pathlib import Path
import sys
import tempfile

from fontTools.merge import Merger
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'frontend/node_modules/@fontsource/ibm-plex-sans-kr/files'
OUT = ROOT/'frontend/src/fonts'
WEIGHTS = (400, 700)
SCAN = [*(ROOT/'frontend/src').rglob('*.js'), *(ROOT/'frontend/src').rglob('*.jsx'), *(ROOT/'frontend/src').rglob('*.json'),
        *(ROOT/'frontend/src').rglob('*.css'), ROOT/'frontend/index.html']


def ks_x_1001_hangul():
    chars = set()
    for lead in range(0xB0, 0xC9):
        for trail in range(0xA1, 0xFF):
            try:
                chars.add(bytes([lead, trail]).decode('euc_kr'))
            except UnicodeDecodeError:
                pass
    assert len(chars) == 2350, len(chars)
    return chars


def app_chars():
    text = ''.join(p.read_text(encoding='utf-8') for p in SCAN if p.is_file() and 'fonts' not in p.parts)
    return {c for c in text if ord(c) >= 0x20 and not c.isspace()} | {' '}


def needed():
    return {chr(c) for c in range(0x20, 0x7F)} | ks_x_1001_hangul() | app_chars()


def slices(weight):
    return sorted(SOURCE.glob(f'ibm-plex-sans-kr-*-{weight}-normal.woff'))


def build(weight, want, tmp):
    parts = []
    for i, path in enumerate(slices(weight)):
        font = TTFont(path)
        keep = {ord(c) for c in want} & set(font.getBestCmap())
        if not keep:
            continue
        options = Options(); options.layout_features = ['*']; options.name_IDs = ['*']; options.notdef_outline = True
        subsetter = Subsetter(options); subsetter.populate(unicodes=keep); subsetter.subset(font)
        font.flavor = None; part = Path(tmp)/f'{weight}-{i}.ttf'; font.save(part); parts.append(str(part))
    merged = Merger().merge(parts)
    merged.flavor = 'woff'
    OUT.mkdir(parents=True, exist_ok=True)
    target = OUT/f'ibm-plex-sans-kr-subset-{weight}.woff'
    merged.save(target)
    return target, set(merged.getBestCmap())


def css():
    rules = [f"""@font-face{{font-family:'IBM Plex Sans KR';font-style:normal;font-display:swap;font-weight:{w};
 src:url('./ibm-plex-sans-kr-subset-{w}.woff') format('woff');}}""" for w in WEIGHTS]
    header = '/* Generated by scripts/build_font_subset.py: KS X 1001 Hangul + ASCII + app text. IBM Plex Sans KR, SIL OFL 1.1. */'
    (OUT/'fonts.css').write_text(header + '\n' + '\n'.join(rules) + '\n', encoding='utf-8')


def report(covered):
    app = app_chars()
    missing_in_subset = sorted(c for c in app if ord(c) not in covered)
    original = set()
    for path in slices(400):
        original |= set(TTFont(path).getBestCmap())
    not_in_font = [c for c in missing_in_subset if ord(c) not in original]
    return {'app_chars': len(app), 'missing_in_subset': [f'U+{ord(c):04X} {c}' for c in missing_in_subset if ord(c) in original],
            'not_in_original_font_uses_system_fallback': [f'U+{ord(c):04X} {c}' for c in not_in_font]}


def check():
    bad = {}
    for w in WEIGHTS:
        path = OUT/f'ibm-plex-sans-kr-subset-{w}.woff'
        if not path.exists():
            print(f'missing {path}'); return 1
        result = report(set(TTFont(path).getBestCmap()))
        if result['missing_in_subset']:
            bad[w] = result['missing_in_subset']
    print(json.dumps(bad or 'all app characters covered', ensure_ascii=False))
    return 1 if bad else 0


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    if args.check:
        sys.exit(check())
    want = needed(); summary = {}
    with tempfile.TemporaryDirectory() as tmp:
        for w in WEIGHTS:
            target, covered = build(w, want, tmp)
            summary[w] = {'file': target.name, 'bytes': target.stat().st_size, 'codepoints': len(covered)} | report(covered)
    css()
    (OUT/'subset-report.json').write_text(json.dumps(summary, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(json.dumps(summary, ensure_ascii=False))
