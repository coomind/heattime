import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
const header='id,round,team_a,team_b,venue_id,scheduled_start,duration_min,depends_on\n';
test('CSV preview, cancel, invalid input and confirmed save remain separate',async({page})=>{
 const id='csv-'+randomUUID(),mid=id+'-match',a=id+'-a',b=id+'-b';
 const tour=await (await page.request.get('/api/tournaments/demo')).json();
 expect((await page.request.post('/api/tournaments',{data:{...tour,id,name:'가상 예시 CSV 검증 대회'}})).status()).toBe(201);
 for(const tid of [a,b])expect((await page.request.post('/api/teams',{data:{id:tid,tournament_id:id,name:'가상 예시 CSV 팀'}})).status()).toBe(201);
 const match=await (await page.request.get('/api/matches/g1-1')).json();
 expect((await page.request.post('/api/matches',{data:{...match,id:mid,tournament_id:id,team_a:a,team_b:b,scheduled_start:'2026-08-01T10:00:00+09:00',depends_on:[]}})).status()).toBe(201);
 const valid=header+mid+',group,'+a+','+b+',mock-suwon-a,2026-08-01T09:00:00+09:00,40,\n';
 await page.goto('/');await page.getByLabel('대회',{exact:true}).selectOption(id);
 await page.locator('nav').getByRole('button',{name:/설정$/}).click();
 const box=page.getByRole('region',{name:'CSV 저장 전 미리보기'}),file=box.locator('input[type=file]');
 const before=await (await page.request.get('/api/matches/'+mid)).json();
 await file.setInputFiles({name:'preview.csv',mimeType:'text/csv',buffer:Buffer.from(valid)});
 await expect(box.getByRole('table',{name:'CSV 저장 예정 경기'})).toContainText('기존 경기 수정');
 await expect(box.getByRole('button',{name:'확인한 CSV 저장',exact:true})).toBeEnabled();
 expect(await (await page.request.get('/api/matches/'+mid)).json()).toEqual(before);
 await box.getByRole('button',{name:'CSV 확인 취소',exact:true}).click();
 await expect(box.getByRole('table')).toHaveCount(0);
 expect(await (await page.request.get('/api/matches/'+mid)).json()).toEqual(before);
 await file.setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from(valid.replace(',40,\n',',40,,extra\n'))});
 await expect(box.getByRole('alert')).toContainText('행 2');
 await expect(box.getByRole('button',{name:'확인한 CSV 저장',exact:true})).toBeDisabled();
 expect(await (await page.request.get('/api/matches/'+mid)).json()).toEqual(before);
 await file.setInputFiles({name:'valid.csv',mimeType:'text/csv',buffer:Buffer.from(valid)});
 await expect(box.getByRole('button',{name:'확인한 CSV 저장',exact:true})).toBeEnabled();
 await box.getByRole('button',{name:'확인한 CSV 저장',exact:true}).click();
 await expect(page.getByText('CSV 대진을 저장했습니다.',{exact:true})).toBeVisible();
 expect((await (await page.request.get('/api/matches/'+mid)).json()).scheduled_start).toBe('2026-08-01T09:00:00+09:00');
 const download=page.waitForEvent('download');await box.getByRole('link',{name:'CSV 양식 내려받기'}).click();
 expect(await (await download).failure()).toBeNull();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
